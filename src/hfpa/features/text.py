"""Model-card text as a demand signal (P18): what the child says it is for, compared with each candidate's card.

Two leaks have to be removed before child and candidate texts are compared:
  names      child cards name their parent ("a fine-tuned version of Qwen/Qwen2.5-7B"). Model ids, organisation
             names, family names (first token of the repo names of parent-side models) and every token with a
             digit (7b, qwen2, v1) are dropped on both sides.
  templates  paragraphs copied from parent cards or generated by tools. A child paragraph is dropped if it
             appears (normalised) in any parent-side card, or in >= MAX_PARA_DF cards overall. The rule is the
             same for every candidate and does not look at which parent was chosen.
Text side: markdown and html markup, code, urls, tables and the YAML front matter are removed first.
Similarity: TF-IDF (sublinear tf, smooth idf, L2) over word tokens (Latin letters) and CJK character bigrams;
cosine between the child's text and the candidate's text.
"""
import hashlib
import re
from collections import Counter

import numpy as np
import scipy.sparse as sp

FRONT = re.compile(r"\A\s*---\s*\n.*?\n---\s*(\n|\Z)", re.S)
CODE = re.compile(r"```.*?(```|\Z)|~~~.*?(~~~|\Z)", re.S)
INLINE = re.compile(r"`[^`\n]*`")
COMMENT = re.compile(r"<!--.*?-->", re.S)
TAG = re.compile(r"<[^>\n]{0,500}>")
IMG = re.compile(r"!\[[^\]]*\]\([^)]*\)")
LINK = re.compile(r"\[([^\]]*)\]\([^)]*\)")
URL = re.compile(r"(https?://|www\.)\S+")
ID = re.compile(r"\b[\w.-]+/[\w.-]+\b")  # org/name ids, also paths
LATIN = re.compile(r"[a-z][a-z0-9]*(?:[.'-][a-z0-9]+)*")
CJK = re.compile(r"[぀-ヿ㐀-䶿一-鿿가-힯]+")
MAX_RAW = 40_000
MAX_CLEAN = 6_000
MAX_PARA_DF = 20
MIN_TOKENS = 5
STOP = set("""a an and are as at be been by can for from has have in into is it its of on or that the this to was
were will with you your we our use used using model models fine tuned tune tuning finetuned version trained train
training based base more information needed card
achieves following results evaluation set loss unknown dataset datasets description intended uses limitations procedure
hyperparameters framework versions details developed funded shared optional type language languages license sources
repository paper demo direct downstream scope bias risks recommendations users should made aware get started code
below data factors metrics testing environmental impact hardware hours cloud provider compute region carbon emitted
technical specifications architecture objective infrastructure software citation bibtex apa glossary authors contact
summary results""".split())
# size and variant words: they identify a parent's variant (whisper-tiny, codet5-small), not a use
SIZE = set("""tiny mini small medium large xl xxl xlarge huge giant nano micro base v instruct it chat hf distilled
uncased cased""".split())


def clean(card):
    """Card markdown -> plain paragraphs (list of str)."""
    if not isinstance(card, str) or not card:
        return []
    s = card[:MAX_RAW]
    s = FRONT.sub("", s)
    for rx in (CODE, COMMENT, IMG):
        s = rx.sub(" ", s)
    s = LINK.sub(r"\1", s)
    s = TAG.sub(" ", s)
    s = URL.sub(" ", s)
    s = INLINE.sub(" ", s)
    lines = [ln for ln in s.split("\n") if ln.count("|") < 2]  # tables: hyperparameters, results
    paras = re.split(r"\n\s*\n", "\n".join(lines))
    out, n = [], 0
    for p in paras:
        p = re.sub(r"[#>*_=\-]{2,}|^\s*[#>*-]+\s*", " ", p, flags=re.M)
        p = re.sub(r"\s+", " ", p).strip()
        if len(p) < 3:
            continue
        out.append(p)
        n += len(p)
        if n >= MAX_CLEAN:
            break
    return out


def para_key(p):
    """Normalised paragraph hash (letters only, lower case; digits and names vary across copies)."""
    norm = re.sub(r"[^a-z぀-鿿가-힯]+", "", ID.sub("", p.lower()))
    return hashlib.blake2b(norm.encode(), digest_size=8).digest() if len(norm) >= 20 else None


def name_vocab(model_ids, full_ids=()):
    """Tokens that identify a model rather than describe a use: org names and family names (first token of the
    repo name) of `model_ids`, every repo-name token of `full_ids` (the hubs: "coder" in Qwen2.5-Coder), and size /
    variant words. Tokens with digits are dropped separately."""
    v = set(SIZE)
    split = lambda x: [w for t in LATIN.findall(x.replace("_", "-")) for w in re.split(r"[.'-]", t) if w]
    for mid in model_ids:
        org, _, repo = str(mid).lower().partition("/")
        v.update(split(org))
        toks = split(repo)
        if toks:
            v.add(toks[0])
            v.add(re.match(r"[a-z]*", toks[0]).group())  # qwen2 -> qwen
    for mid in full_ids:
        org, _, repo = str(mid).lower().partition("/")
        v.update(split(org))
        v.update(split(repo))
        v.update(re.match(r"[a-z]*", t).group() for t in split(repo))
    return v - STOP - {""}


def tokens(paras, names):
    s = ID.sub(" ", " ".join(paras).lower())
    out = []
    for t in LATIN.findall(s):
        for w in re.split(r"[.'-]", t):
            if len(w) >= 2 and w not in STOP and w not in names and not any(c.isdigit() for c in w):
                out.append(w)
    for run in CJK.findall(s):
        out.extend(run[i:i + 2] for i in range(len(run) - 1))
    return out


def tfidf(docs, min_df=5, max_df=0.5):
    """docs: iterable of token lists. Returns L2-normalised csr matrix (rows = docs) and the vocabulary."""
    vocab, ids, cnts, indptr = {}, [], [], [0]
    for d in docs:
        c = Counter(d)
        ids.append(np.fromiter((vocab.setdefault(t, len(vocab)) for t in c), np.int32, len(c)))
        cnts.append(np.fromiter(c.values(), np.float32, len(c)))
        indptr.append(indptr[-1] + len(c))
    n = len(indptr) - 1
    X = sp.csr_matrix((np.concatenate(cnts) if cnts else np.zeros(0, np.float32),
                       np.concatenate(ids) if ids else np.zeros(0, np.int32), np.array(indptr, np.int64)),
                      shape=(n, len(vocab)))
    df = np.bincount(X.indices, minlength=len(vocab))
    keep = (df >= min_df) & (df <= max_df * n)
    X = X[:, keep]
    idf = np.log((1 + n) / (1 + df[keep])) + 1
    X.data = np.log1p(X.data)
    X = X @ sp.diags(idf.astype(np.float32))
    norm = np.sqrt(np.asarray(X.multiply(X).sum(1)).ravel())
    X = sp.diags(np.where(norm > 0, 1 / np.maximum(norm, 1e-12), 0).astype(np.float32)) @ X
    inv = np.array(list(vocab))[keep]
    return X.tocsr(), inv


def row_cosine(X, a, b, chunk=1_000_000):
    """Cosine between rows X[a[k]] and X[b[k]] (rows already L2-normalised)."""
    out = np.zeros(len(a), np.float32)
    for s in range(0, len(a), chunk):
        e = min(s + chunk, len(a))
        out[s:e] = np.asarray(X[a[s:e]].multiply(X[b[s:e]]).sum(1)).ravel()
    return out


def drop_templates(paras, banned):
    """Paragraphs whose normalised key is not in `banned` (keys of parent-side or very frequent paragraphs)."""
    return [p for p in paras if para_key(p) not in banned]
